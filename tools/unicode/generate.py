"""Generate C++ tables from the pinned Unicode 16.0 and 9.0 UCD archives."""

import hashlib
from pathlib import Path
import zipfile


ARCHIVES = {
    "9.0.0": "df9e028425816fd5117eaea7173704056f88f7cd030681e457c6f3827f9390ec",
    "16.0.0": "c86dd81f2b14a43b0cc064aa5f89aa7241386801e35c59c7984e579832634eb2",
}


def open_ucd(directory, version):
    path = directory / f"UCD-{version}.zip"
    if hashlib.sha256(path.read_bytes()).hexdigest() != ARCHIVES[version]:
        raise ValueError(f"UCD digest mismatch: {path}")
    return zipfile.ZipFile(path)


def records(archive, filename):
    for line in archive.read(filename).decode("utf-8").splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            yield [field.strip() for field in data.split(";")]


def interval(text):
    first, _, last = text.partition("..")
    return range(int(first, 16), int(last or first, 16) + 1)


def properties(ucd):
    entries = {}
    start = None
    for point, name, category, *_ in records(ucd, "UnicodeData.txt"):
        point = int(point, 16)
        flags = {"L": 1, "M": 2, "N": 4}.get(category[0], 0)
        if name.endswith(", First>"):
            start = point
            continue
        points = range(start if start is not None else point, point + 1)
        if flags:
            entries.update(dict.fromkeys(points, flags))
        start = None
    for points, name in records(ucd, "PropList.txt"):
        if name == "White_Space":
            for point in interval(points):
                entries[point] = entries.get(point, 0) | 8
    result = []
    for point, flags in sorted(entries.items()):
        if result and result[-1][1] + 1 == point and result[-1][2] == flags:
            result[-1] = (result[-1][0], point, flags)
        else:
            result.append((point, point, flags))
    return result


def contraction_folds(ucd):
    contractions = ("s", "t", "re", "ve", "m", "ll", "d")
    letters = set("".join(contractions))
    result = []
    for point, status, mapping, *_ in records(ucd, "CaseFolding.txt"):
        folded = "".join(chr(int(item, 16)) for item in mapping.split())
        if status == "F" and any(folded in word for word in contractions):
            raise ValueError(f"full case fold can match a contraction: {point}")
        if status in {"C", "S"} and folded in letters:
            result.append((int(point, 16), ord(folded)))
    return sorted(result)


def nfc_tables(ucd):
    excluded = set()
    for points, prop, *_ in records(ucd, "DerivedNormalizationProps.txt"):
        if prop == "Full_Composition_Exclusion":
            excluded.update(interval(points))
    classes, decompositions, compositions = [], [], []
    for point, _, _, combining, _, mapping, *_ in records(ucd, "UnicodeData.txt"):
        point = int(point, 16)
        if int(combining):
            classes.append((point, int(combining)))
        if not mapping or mapping.startswith("<"):
            continue
        parts = [int(item, 16) for item in mapping.split()]
        if len(parts) not in (1, 2):
            raise ValueError(f"unexpected canonical decomposition: {point:x}")
        decompositions.append((point, *parts, *([0] if len(parts) == 1 else [])))
        if point not in excluded:
            if len(parts) != 2:
                raise ValueError(f"unexpected NFC composition: {point:x}")
            compositions.append((*parts, point))
    return classes, decompositions, sorted(compositions)


def emit(output, kind, name, rows):
    output.write(f"constexpr {kind} {name}[] = {{\n")
    line = "   "
    for row in rows:
        record = " {" + ", ".join(f"0x{value:x}" for value in row) + "},"
        if len(line) + len(record) > 96:
            output.write(line + "\n")
            line = "   "
        line += record
    output.write(line + "\n")
    output.write("};\n")


def write_table(directory, stem, *tables):
    path = directory / f"{stem}.h"
    with path.open("w", encoding="ascii", newline="\n") as output:
        output.write("// Generated by tools/unicode/generate.py. See tools/unicode/LICENSE.\n\n")
        for index, (kind, name, rows) in enumerate(tables):
            if index:
                output.write("\n")
            emit(output, kind, name, rows)


def main():
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("sources", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with open_ucd(args.sources, "16.0.0") as recent, open_ucd(args.sources, "9.0.0") as old:
        classes, decompositions, compositions = nfc_tables(old)
        args.output.mkdir(parents=True, exist_ok=True)
        write_table(
            args.output, "character_properties_16",
            ("PropertyRange", "properties_16", properties(recent)),
            ("ScalarPair", "contraction_folds_16", contraction_folds(recent)),
        )
        write_table(args.output, "combining_classes_9", ("ScalarPair", "classes_9", classes))
        write_table(
            args.output, "canonical_decompositions_9",
            ("Mapping", "decompositions_9", decompositions),
        )
        write_table(
            args.output, "canonical_compositions_9", ("Mapping", "compositions_9", compositions),
        )


if __name__ == "__main__":
    main()
